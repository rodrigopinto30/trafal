const COUNTRY_SET = new Set(ISO_COUNTRY_CODES);

export function isCountryCode(code: string): boolean {
  return COUNTRY_SET.has(code);
}

/** Lista de países para el selector, con el nombre en el idioma de la interfaz y ordenada alfabéticamente. */
export function countryOptions(locale: string): { code: string; name: string }[] {
  const names = new Intl.DisplayNames([locale], { type: "region" });
  return ISO_COUNTRY_CODES.map((code) => ({ code, name: names.of(code) ?? code })).sort((x, y) =>
    x.name.localeCompare(y.name, locale),
  );
}
